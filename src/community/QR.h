static inline bool modulo(const uint8_t* datos, uint8_t tam, uint8_t x, uint8_t y) {
  const uint16_t indice = (uint16_t)y * tam + x;
  const uint8_t valor = pgm_read_byte(datos + (indice >> 3));
  return ((valor >> (7 - (indice & 7))) & 1U) != 0;
}

template <typename Pantalla>
void dibujarMatriz(Pantalla &destino,
                   const uint8_t* datos,
                   uint8_t tam,
                   int centroX,
                   int centroY,
                   int maximoPx,
                   uint16_t colorOscuro = TFT_BLACK,
                   uint16_t colorClaro = TFT_WHITE) {
  const int margen = 4;  // zona silenciosa obligatoria del QR
  const int modulosTotales = tam + margen * 2;
  int escala = maximoPx / modulosTotales;
  if (escala < 1) escala = 1;

  const int lado = modulosTotales * escala;
  const int origenX = centroX - lado / 2;
  const int origenY = centroY - lado / 2;

  destino.fillRect(origenX, origenY, lado, lado, colorClaro);

  for (uint8_t y = 0; y < tam; ++y) {
    for (uint8_t x = 0; x < tam; ++x) {
      if (modulo(datos, tam, x, y)) {
        destino.fillRect(origenX + (x + margen) * escala,
                         origenY + (y + margen) * escala,
                         escala, escala, colorOscuro);
      }
    }
  }
}

